export function isMandy(user: Pick<SessionUser, "email" | "piPrefix">) {
  return user.piPrefix.trim().toLowerCase() === "mandy" || user.email.trim().toLowerCase() === "mandy@quoteflow.local";
}

export function pickMandyMessage<T extends readonly string[]>(messages: T, seed: string) {
  let hash = 0;
  for (const character of seed) hash = (hash * 31 + character.charCodeAt(0)) >>> 0;
  return messages[hash % messages.length];
}
